import type { SupabaseClient } from "@supabase/supabase-js";
import type {
  DocumentsStatus,
  NewVehicleInput,
  Vehicle,
} from "@/types/database";

import { normaliseField as normalise } from "./normalise";

export class ActionError extends Error {}


/** Data-entry: insert a new vehicle. RLS forces status = 'pending'. */
export async function addVehicle(
  supabase: SupabaseClient,
  input: NewVehicleInput
): Promise<Vehicle> {
  const { data, error } = await supabase
    .from("vehicles")
    .insert({
      registration_no: normalise(input.registration_no),
      chassis_no: normalise(input.chassis_no),
      engine_no: normalise(input.engine_no),
      documents_status: input.documents_status,
      status: "pending",
    })
    .select()
    .single();

  if (error) {
    if (error.code === "23505") {
      throw new ActionError("This number plate is already in the pending queue.");
    }
    throw new ActionError(error.message);
  }
  return data as Vehicle;
}

/**
 * Inspector action: Pass or Fail a pending vehicle.
 *
 * The certificate number, inspector name and timestamp are generated by the
 * `vehicles_before_update` database trigger — the client only sends the
 * decision and remarks, so none of it can be forged from the browser.
 */
export async function inspectVehicle(
  supabase: SupabaseClient,
  args: { id: string; decision: "passed" | "failed"; remarks?: string }
): Promise<Vehicle> {
  const remarks = args.remarks?.trim() || null;
  if (args.decision === "failed" && !remarks) {
    throw new ActionError("Please enter the reason for failing this vehicle.");
  }

  const { data, error } = await supabase
    .from("vehicles")
    .update({ status: args.decision, remarks })
    .eq("id", args.id)
    .eq("status", "pending")
    .select()
    .single();

  if (error) {
    if (error.code === "PGRST116") {
      throw new ActionError(
        "Could not update: the record was already processed or you lack permission."
      );
    }
    throw new ActionError(error.message);
  }
  return data as Vehicle;
}

/** Inspector action: toggle document verification on a pending vehicle. */
export async function setDocumentsStatus(
  supabase: SupabaseClient,
  id: string,
  documents_status: DocumentsStatus
): Promise<Vehicle> {
  const { data, error } = await supabase
    .from("vehicles")
    .update({ documents_status })
    .eq("id", id)
    .eq("status", "pending")
    .select()
    .single();
  if (error) throw new ActionError(error.message);
  return data as Vehicle;
}

export interface ImportRow extends NewVehicleInput {
  /** Row number in the uploaded file, used for error reporting */
  line: number;
}

export interface ImportResult {
  inserted: Vehicle[];
  failed: { line: number; message: string }[];
}

/**
 * Bulk-insert rows into the Pending queue (RLS forces status = 'pending').
 * Inserts in chunks; if a chunk is rejected, falls back to row-by-row so one
 * bad row does not block the rest.
 */
export async function importVehicles(
  supabase: SupabaseClient,
  rows: ImportRow[]
): Promise<ImportResult> {
  const inserted: Vehicle[] = [];
  const failed: ImportResult["failed"] = [];
  const CHUNK = 200;

  for (let i = 0; i < rows.length; i += CHUNK) {
    const chunk = rows.slice(i, i + CHUNK);
    const payload = chunk.map((r) => ({
      registration_no: normalise(r.registration_no),
      chassis_no: normalise(r.chassis_no),
      engine_no: normalise(r.engine_no),
      documents_status: r.documents_status,
      status: "pending",
    }));

    const { data, error } = await supabase.from("vehicles").insert(payload).select();
    if (!error) {
      inserted.push(...((data ?? []) as Vehicle[]));
      continue;
    }

    // The failed batch inserted nothing (atomic) — retry one by one.
    for (let j = 0; j < chunk.length; j++) {
      const { data: one, error: err } = await supabase
        .from("vehicles")
        .insert(payload[j])
        .select()
        .single();
      if (err) {
        failed.push({
          line: chunk[j].line,
          message:
            err.code === "23505" ? "Number plate is already in the pending queue" : err.message,
        });
      } else {
        inserted.push(one as Vehicle);
      }
    }
  }
  return { inserted, failed };
}
